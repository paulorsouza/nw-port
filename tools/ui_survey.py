"""Survey of the game's LyShine screens: structure, texts and textures of each canvas.

    python3 tools/ui_survey.py [canvas...] > extract/ui/survey.md
    NW_LANG=pt-br python3 tools/ui_survey.py ...      # text values in another language (default en-us)

Without arguments: the screens in the HUD list below. Reads extract/ui/lyshineui/**/<name>.dynamicuicanvas.json
(through tools/ui_canvas.py, the converter the ui_build_*.py use) and writes markdown: first- and second-level
elements with anchors/offsets, @key texts translated, textures used and attached Lua scripts. The output holds text
from the game's files: keep it in extract/, never in the repository.
"""
import collections
import glob
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, "extract", "ui")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ui_build_mastery import load_loc  # noqa: E402

HUD = ["escapemenu", "options", "equipmentv3", "paperdollstatuscanvas", "xp", "encumbrance", "compass", "navbar",
       "tooltip", "interactscreen", "lootticker2024", "damagenumbers", "targetlock", "statuseffectsv2",
       "notification", "warningbar", "magicmap", "actionbar", "vitals2024", "weaponquickslots",
       "consumablequickslots", "newinventory", "hitindicator", "afflictions2024"]


def find(name):
    hits = glob.glob(os.path.join(UI, "lyshineui", "**", f"{name}.dynamicuicanvas.json"), recursive=True)
    return hits[0] if hits else None


def convert(path):
    tmp = os.path.join(UI, "survey", os.path.basename(path).split(".")[0] + ".flat.json")
    os.makedirs(os.path.dirname(tmp), exist_ok=True)
    if not os.path.exists(tmp) or os.path.getmtime(tmp) < os.path.getmtime(path):
        subprocess.run(["python3", os.path.join(ROOT, "tools", "ui_canvas.py"), path, tmp, "--tex", os.path.join(UI, "tex")],
                       check=True, capture_output=True)
    return json.load(open(tmp))


def main():
    names = sys.argv[1:] or HUD
    loc = load_loc(os.environ.get("NW_LANG", "en-us"))
    print("# Survey of the game's screens (generated by tools/ui_survey.py; regenerating overwrites this file)\n")
    for name in names:
        path = find(name)
        if not path:
            print(f"## {name}\n\nnot found\n")
            continue
        lay = convert(path)
        els = lay["elements"]
        rel = os.path.relpath(path, os.path.join(UI))
        print(f"## {name}\n\n`{rel}` — {len(els)} elements, screen {lay['size'][0]}x{lay['size'][1]}\n")
        tops = [e for e in els if e["path"].count("/") in (1, 2)]
        print("| element | enabled | anchors | offsets |\n|---|---|---|---|")
        for e in tops[:40]:
            ind = "&nbsp;&nbsp;" * (e["path"].count("/") - 1)
            print(f"| {ind}{e['path'].split('/')[-1]} | {'yes' if e.get('enabled', True) else 'no'} | "
                  f"{[round(v, 2) for v in e.get('anchors', [])]} | {[round(v) for v in e.get('offsets', [])]} |")
        if len(tops) > 40:
            print(f"| … {len(tops) - 40} more | | | |")
        texts = collections.OrderedDict()
        for e in els:
            t = (e.get("text") or {}).get("text") or ""
            if t.startswith("@"):
                texts[t] = loc.get(t[1:].lower(), "?")
        if texts:
            print("\nTexts: " + "; ".join(f"`{k}` = {v}" for k, v in list(texts.items())[:30]))
        tex = sorted({e["image"]["texture"] for e in els if e.get("image") and e["image"].get("texture")})
        if tex:
            print(f"\nTextures ({len(tex)}): " + ", ".join(f"`{t.split('/')[-1]}`" for t in tex[:25]) + (" …" if len(tex) > 25 else ""))
        scripts = sorted({s.split('"')[0] for e in els for s in (e.get("scripts") or []) if isinstance(s, str)})
        if scripts:
            print("\nLua: " + ", ".join(f"`{s}`" for s in scripts[:15]))
        print()


if __name__ == "__main__":
    main()
